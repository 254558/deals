/**
 * 按**品类**给商品分堆，好让尺码表分组显示。
 *
 * 用户 2026-10-05 的三次调整，按时间记在这里，免得以后又绕回去：
 *   1. 「尺码按 衣服/裤子/鞋子/内衣/其他 分类」→ 于是有了分组；
 *   2. 「上衣和外套有什么区别，归为一类」→ 外套并进衣服（实测两者尺码集合一样，各 15 种）；
 *   3. 「鞋不用管，像袜子围巾鞋这种小众的东西就不统计尺码了」→
 *      **只有核心服装统计尺码**（见 SIZE_CATS），鞋、袜、围巾、帽子、包这些不进尺码表。
 *
 * 为什么要分组：S/M/L 在衣服、裤子、内衣里是**重复**的，几十个尺码平铺成一列谁也找不着。
 * 分堆之后「裤子 · M」才表达得出来 —— 这颗按钮筛的也是「这个品类里的这个尺码」。
 *
 * 为什么只能靠商品名：payload 里没有品类字段（见 docs/MAP.md 的抓取部分）。
 * 而且**光看尺码也分不出来**，cm 那套值是几种完全不同的量（实测 uniqlo 的 249 件）：
 *   53–91    裤子的腰围　　97–122  裤长（加长款）　　110–160  童装的身高
 * 所以**不能**把 cm 统一换算成 XS/XL —— 76cm 的腰围不是 M，硬套等于编数据。
 * 能做的、也确实有用的是给 cm 补上「它是什么」（见 CM_HINT）。
 *
 * 规则是「越具体越先判」，**顺序本身就是规则**：
 *   裙子 → 内衣 → 裤子 → 衣服 → 其他
 * 例：「打底裤」撞不上内衣任何词，才落到裤子；「连裤袜」撞上内衣的「袜」→ 但它属于小众，
 *     所以下面把袜挪出内衣、进「其他」，于是它不再计入任何尺码表。
 */
const RULES = [
  ['裙子', /裙/],
  ['内衣', /内裤|文胸|胸罩|bra|内衣|睡衣|家居服|秋衣|保暖内衣|打底衫/i],
  ['裤子', /裤|打底|legging/i],
  ['衣服', /外套|夹克|茄克|羽绒|大衣|风衣|棉服|马甲|派克|T恤|T恤衫|tee|衬衫|衬衣|针织|毛衣|卫衣|背心|吊带|POLO|开衫|套头|上衣/i],
];

/**
 * **只有这四个品类统计尺码**（用户 2026-10-05：「鞋不用管，像袜子围巾鞋啊
 * 乱七八糟小众的东西就不统计尺码了」）。
 * 分类函数仍会给每件东西归堆（鞋、袜、围巾、帽、包…都归「其他」），
 * 只是「其他」不进尺码表 —— 几双袜子、一条围巾的尺码没有统计价值，
 * 摆上去只会把真正要找的衣服尺码冲淡。
 */
export const SIZE_CATS = ['衣服', '裤子', '裙子', '内衣'];

/** 给 cm 尺码补上「它是什么」。不换算成 XS/XL —— 那不是同一种量 */
export const CM_HINT = {
  衣服: 'cm 是童装身高',
  裤子: 'cm 是腰围 / 裤长',
  裙子: 'cm 是身高 / 裙长',
  内衣: 'cm 是童装身高',
};

/** 这个尺码标签是不是 cm 那种 */
export const isCm = (label) => /cm$/i.test(label);

export function categoryOf(name = '') {
  for (const [cat, re] of RULES) if (re.test(name)) return cat;
  return '其他';
}

/** 尺码排序：服装惯例 XS→4XL 在前，其余（cm 那些）按字典序跟在后面 */
export const SIZES_ORDER = ['XS', 'S', 'M', 'L', 'XL', 'XXL', '3XL', '4XL'];
export function sizeRank(s) {
  const k = SIZES_ORDER.indexOf(s);
  return k < 0 ? 99 : k;
}
