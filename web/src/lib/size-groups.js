/**
 * 按**品类**给商品分堆，好让尺码表分组显示（用户 2026-10-05 要「尺码按 衣服/裤子/鞋子/
 * 内衣/其他 分类」，并说「你有更好的分类也可以」）。
 *
 * 为什么要分：S/M/L 在上衣、裤子、内衣里是**重复**的，66 个尺码平铺成一列谁也找不着。
 * 分堆之后「裤子 · M」才表达得出来 —— 这颗按钮筛的也是「这个品类里的这个尺码」。
 *
 * 为什么只能靠商品名：payload 里没有品类字段（见 docs/MAP.md 的抓取部分）。
 * 而且**光看尺码也分不出来** —— cm 标签是歧义的：
 *   70cm/76cm = 裤子的腰围裤长、80cm = 裙子、110cm = 童装身高、22.5cm = 鞋码。
 *
 * 所以规则是「越具体越先判」，顺序本身就是规则的一部分：
 *   鞋子 → 裙子 → 内衣 → 裤子 → 外套 → 上衣 → 其他
 * 例：「连裤袜」先撞上内衣的「袜」（它确实是袜子），不会被裤子的「裤」抢走；
 *     「打底裤」撞不上内衣任何词，才落到裤子。
 * 认不出来的一律进「其他」—— 宁可承认不知道，也别把羽绒服塞进裤子里。
 */
const RULES = [
  ['鞋子', /鞋|靴|拖鞋|凉鞋|帆布/],
  ['裙子', /裙/],
  ['内衣', /内裤|文胸|胸罩|bra|内衣|袜|睡衣|家居服|秋衣|保暖内衣/i],
  ['裤子', /裤|打底|legging/i],
  ['外套', /外套|夹克|茄克|羽绒|大衣|风衣|棉服|马甲|派克/],
  ['上衣', /T恤|T恤衫|tee|衬衫|衬衣|针织|毛衣|卫衣|背心|吊带|POLO|开衫|套头|上衣|打底衫/i],
];

/** 面板里的分组顺序（也是「其他」兜底的位置） */
export const CATS = ['上衣', '外套', '裤子', '裙子', '内衣', '鞋子', '其他'];

export function categoryOf(name = '') {
  for (const [cat, re] of RULES) if (re.test(name)) return cat;
  return '其他';
}

/** 尺码排序：服装惯例 XS→4XL 在前，其余（cm 那些）按字典序跟在后面 */
export const SIZES_ORDER = ['XS', 'S', 'M', 'L', 'XL', 'XXL', '3XL', '4XL'];
export function sizeRank(s) {
  const k = SIZES_ORDER.indexOf(s);
  return k < 0 ? 99 : k;
}
